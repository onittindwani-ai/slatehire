#!/usr/bin/env python3
"""Compute the tool comparison scores and write the tables into docs/TOOLS-AND-ALTERNATIVES.md.

Reads data/tool_scores.json. Method: the hub COMPARISON-METHOD (six criteria, scored 0 to 100, one evidence line each,
weighted total, closeness = alternative fit divided by reference fit). The scores are judgements, not benchmarks.

Usage:
  python3 tools/score_tools.py            validate, then rewrite the generated block in the doc
  python3 tools/score_tools.py --check    validate and fail if the doc is out of date (used by the tests)
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "tool_scores.json"
DOC = ROOT / "docs" / "TOOLS-AND-ALTERNATIVES.md"
START, END = "<!-- SCORES:START (generated by tools/score_tools.py, do not edit by hand) -->", "<!-- SCORES:END -->"
EXPECTED_WEIGHTS = {"fit": 35, "setup": 15, "reliability": 15, "cost": 15, "data": 10, "integration": 10}
USER_TYPES = (("beginner", "Beginner"), ("implementer", "Implementer running it for clients"), ("cost_sensitive", "Cost sensitive owner"), ("open_source_when", "When open source is the right call"))
DASHES = tuple(chr(c) for c in (0x2014, 0x2013, 0x2012, 0x2015))


def validate(data: dict) -> list[str]:
    errs: list[str] = []
    if data.get("weights") != EXPECTED_WEIGHTS:
        errs.append(f"weights must be {EXPECTED_WEIGHTS}")
    if sum(data.get("weights", {}).values()) != 100:
        errs.append("weights must add up to 100")
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(data.get("dated", ""))):
        errs.append("dated must be YYYY-MM-DD")
    seen: set[str] = set()
    for g in data.get("groups", []):
        ids = [t["id"] for t in g["tools"]]
        if g["reference"] not in ids:
            errs.append(f"group {g['id']}: reference {g['reference']} is not one of its tools")
        for key, _ in USER_TYPES:
            if not g.get("recommendation", {}).get(key, "").strip():
                errs.append(f"group {g['id']}: missing recommendation '{key}'")
        for t in g["tools"]:
            if t["id"] in seen:
                errs.append(f"duplicate tool id {t['id']}")
            seen.add(t["id"])
            if not t.get("sources"):
                errs.append(f"{t['id']}: needs at least one source with a date")
            for c in EXPECTED_WEIGHTS:
                cell = t["scores"].get(c)
                if cell is None:
                    errs.append(f"{t['id']}: missing criterion {c}")
                    continue
                if not isinstance(cell["score"], int) or isinstance(cell["score"], bool) or not 0 <= cell["score"] <= 100:
                    errs.append(f"{t['id']}.{c}: score must be a whole number from 0 to 100")
                if len(cell["evidence"].strip()) < 20:
                    errs.append(f"{t['id']}.{c}: write a real evidence line")
            extra = set(t["scores"]) - set(EXPECTED_WEIGHTS)
            if extra:
                errs.append(f"{t['id']}: unknown criteria {sorted(extra)}")
    text = json.dumps(data, ensure_ascii=False)
    if any(d in text for d in DASHES):
        errs.append("no em or en dashes in the data")
    return errs


def total(tool: dict, weights: dict) -> float:
    return round(sum(tool["scores"][c]["score"] * w for c, w in weights.items()) / 100, 1)


def closeness(tool: dict, ref: dict) -> int:
    return round(100 * tool["scores"]["fit"]["score"] / ref["scores"]["fit"]["score"])


def compute(data: dict) -> dict:
    out: dict = {}
    for g in data["groups"]:
        ref = next(t for t in g["tools"] if t["id"] == g["reference"])
        out[g["id"]] = {t["id"]: {"total": total(t, data["weights"]), "closeness": None if t is ref else closeness(t, ref)} for t in g["tools"]}
    return out


def render(data: dict) -> str:
    w, names, calc = data["weights"], data["criteria_names"], compute(data)
    head = "| Tool | Kind | " + " | ".join(f"{names[c]} ({w[c]})" for c in w) + " | Total | Closeness |"
    lines = [f"Scores dated {data['dated']}. {data['note']}", ""]
    for g in data["groups"]:
        ref = next(t for t in g["tools"] if t["id"] == g["reference"])
        lines += [f"### {g['job']}", "", head, "|" + "---|" * (len(w) + 4)]
        for t in g["tools"]:
            c = calc[g["id"]][t["id"]]
            close = "reference" if c["closeness"] is None else f"{c['closeness']} percent of {ref['name']}"
            lines.append(f"| {t['name']} | {t['kind']} | " + " | ".join(str(t["scores"][k]["score"]) for k in w) + f" | **{c['total']}** | {close} |")
        lines += ["", "What Slatehire has for each: " + "; ".join(f"{t['name']}: {t['supported_in_slatehire']} ({t['run']})" for t in g["tools"]) + ".", ""]
        if g.get("no_open_source"):
            lines += ["There is no close open source replacement here that Slatehire supports, so none is scored.", ""]
        for t in g["tools"]:
            lines += [f"**Evidence, {t['name']}**", ""]
            lines += [f"- {names[k]} ({t['scores'][k]['score']}): {t['scores'][k]['evidence']}" for k in w]
            lines += ["- Sources: " + ", ".join(f"{s['url']} (checked {s['checked']})" for s in t["sources"]), ""]
        lines += ["**Recommendation by user type**", ""] + [f"- **{label}:** {g['recommendation'][key]}" for key, label in USER_TYPES] + [""]
    lines += ["### Named but not scored", ""] + [f"- {u['name']}: {u['why']}" for u in data["unscored_named"]] + [""]
    return "\n".join(lines)


def build(doc_text: str, data: dict) -> str:
    a, b = doc_text.index(START), doc_text.index(END)
    return doc_text[: a + len(START)] + "\n\n" + render(data) + "\n" + doc_text[b:]


def main(argv: list[str]) -> int:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    errs = validate(data)
    if errs:
        print("\n".join("PROBLEM " + e for e in errs))
        return 1
    current = DOC.read_text(encoding="utf-8")
    new = build(current, data)
    if "--check" in argv:
        if new != current:
            print("PROBLEM docs/TOOLS-AND-ALTERNATIVES.md is out of date. Run python3 tools/score_tools.py")
            return 1
        print("OK scores and document agree")
        return 0
    DOC.write_text(new, encoding="utf-8")
    print("OK wrote", DOC.relative_to(ROOT), "with", sum(len(g["tools"]) for g in data["groups"]), "tools in", len(data["groups"]), "groups")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
